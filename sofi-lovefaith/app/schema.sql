CREATE TABLE IF NOT EXISTS settings (
  k VARCHAR(100) NOT NULL PRIMARY KEY,
  v MEDIUMTEXT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS pages (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(60) NOT NULL UNIQUE,
  title_en VARCHAR(190) NOT NULL DEFAULT '',
  title_es VARCHAR(190) NOT NULL DEFAULT '',
  blocks MEDIUMTEXT NULL,
  blocks_draft MEDIUMTEXT NULL,
  seo TEXT NULL,
  updated_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS categories (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE,
  name_en VARCHAR(120) NOT NULL DEFAULT '',
  name_es VARCHAR(120) NOT NULL DEFAULT '',
  image VARCHAR(255) NULL,
  sort INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS products (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(160) NOT NULL UNIQUE,
  sku VARCHAR(80) NOT NULL DEFAULT '',
  name_en VARCHAR(190) NOT NULL DEFAULT '',
  name_es VARCHAR(190) NOT NULL DEFAULT '',
  tagline_en VARCHAR(255) NOT NULL DEFAULT '',
  tagline_es VARCHAR(255) NOT NULL DEFAULT '',
  description_en MEDIUMTEXT NULL,
  description_es MEDIUMTEXT NULL,
  details_en TEXT NULL,
  details_es TEXT NULL,
  price DECIMAL(10,2) NOT NULL DEFAULT 0,
  compare_price DECIMAL(10,2) NULL,
  cost DECIMAL(10,2) NULL,
  stock INT NOT NULL DEFAULT 0,
  track_stock TINYINT(1) NOT NULL DEFAULT 1,
  allow_backorder TINYINT(1) NOT NULL DEFAULT 0,
  categories VARCHAR(255) NOT NULL DEFAULT '',
  type VARCHAR(60) NOT NULL DEFAULT '',
  material VARCHAR(255) NOT NULL DEFAULT '',
  tags VARCHAR(255) NOT NULL DEFAULT '',
  badge_en VARCHAR(40) NOT NULL DEFAULT '',
  badge_es VARCHAR(40) NOT NULL DEFAULT '',
  status VARCHAR(20) NOT NULL DEFAULT 'draft',
  featured TINYINT(1) NOT NULL DEFAULT 0,
  sort INT NOT NULL DEFAULT 0,
  sale_ends_at DATETIME NULL,
  options TEXT NULL,
  variants MEDIUMTEXT NULL,
  boosters TEXT NULL,
  bundle_ids VARCHAR(255) NOT NULL DEFAULT '',
  seo TEXT NULL,
  created_at DATETIME NULL,
  updated_at DATETIME NULL,
  KEY idx_status (status),
  KEY idx_sort (sort)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS product_media (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  product_id INT UNSIGNED NOT NULL,
  path VARCHAR(500) NOT NULL,
  kind VARCHAR(10) NOT NULL DEFAULT 'image',
  poster VARCHAR(500) NULL,
  alt_en VARCHAR(255) NOT NULL DEFAULT '',
  alt_es VARCHAR(255) NOT NULL DEFAULT '',
  sort INT NOT NULL DEFAULT 0,
  KEY idx_product (product_id, sort)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS media (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  path VARCHAR(500) NOT NULL,
  kind VARCHAR(10) NOT NULL DEFAULT 'image',
  mime VARCHAR(100) NOT NULL DEFAULT '',
  size INT UNSIGNED NOT NULL DEFAULT 0,
  width INT UNSIGNED NULL,
  height INT UNSIGNED NULL,
  original VARCHAR(255) NOT NULL DEFAULT '',
  created_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS orders (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  number VARCHAR(30) NOT NULL UNIQUE,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  email VARCHAR(190) NOT NULL DEFAULT '',
  name VARCHAR(190) NOT NULL DEFAULT '',
  phone VARCHAR(60) NOT NULL DEFAULT '',
  address TEXT NULL,
  items MEDIUMTEXT NULL,
  gift_message TEXT NULL,
  subtotal DECIMAL(10,2) NOT NULL DEFAULT 0,
  discount DECIMAL(10,2) NOT NULL DEFAULT 0,
  shipping DECIMAL(10,2) NOT NULL DEFAULT 0,
  total DECIMAL(10,2) NOT NULL DEFAULT 0,
  currency VARCHAR(3) NOT NULL DEFAULT 'USD',
  coupon VARCHAR(60) NOT NULL DEFAULT '',
  stripe_session VARCHAR(255) NOT NULL DEFAULT '',
  lang VARCHAR(2) NOT NULL DEFAULT 'en',
  note TEXT NULL,
  created_at DATETIME NULL,
  paid_at DATETIME NULL,
  KEY idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS submissions (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  form VARCHAR(30) NOT NULL DEFAULT 'contact',
  name VARCHAR(190) NOT NULL DEFAULT '',
  email VARCHAR(190) NOT NULL DEFAULT '',
  phone VARCHAR(60) NOT NULL DEFAULT '',
  subject VARCHAR(190) NOT NULL DEFAULT '',
  message TEXT NULL,
  newsletter TINYINT(1) NOT NULL DEFAULT 0,
  lang VARCHAR(2) NOT NULL DEFAULT 'en',
  page VARCHAR(190) NOT NULL DEFAULT '',
  status VARCHAR(20) NOT NULL DEFAULT 'new',
  note TEXT NULL,
  ip VARCHAR(45) NOT NULL DEFAULT '',
  created_at DATETIME NULL,
  KEY idx_form (form, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS reviews (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  product_id INT UNSIGNED NOT NULL,
  name VARCHAR(120) NOT NULL DEFAULT '',
  email VARCHAR(190) NOT NULL DEFAULT '',
  rating TINYINT NOT NULL DEFAULT 5,
  title VARCHAR(190) NOT NULL DEFAULT '',
  body TEXT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  created_at DATETIME NULL,
  KEY idx_product (product_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS coupons (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(60) NOT NULL UNIQUE,
  type VARCHAR(10) NOT NULL DEFAULT 'percent',
  value DECIMAL(10,2) NOT NULL DEFAULT 0,
  min_total DECIMAL(10,2) NOT NULL DEFAULT 0,
  category VARCHAR(80) NOT NULL DEFAULT '',
  active TINYINT(1) NOT NULL DEFAULT 1,
  expires_at DATETIME NULL,
  uses INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS login_attempts (
  ip VARCHAR(45) NOT NULL PRIMARY KEY,
  attempts INT NOT NULL DEFAULT 0,
  locked_until DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
